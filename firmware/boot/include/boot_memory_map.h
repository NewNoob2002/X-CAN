#ifndef XCAN_BOOT_MEMORY_MAP_H
#define XCAN_BOOT_MEMORY_MAP_H

#define XCAN_FLASH_BASE 0x08000000U
#define XCAN_FLASH_END 0x08020000U
#define XCAN_FLASH_PAGE_SIZE 0x00000800U
#define XCAN_FLASH_WRITE_SIZE 8U

#define XCAN_BOOT_BASE 0x08000000U
#define XCAN_BOOT_SIZE 0x00006000U
#define XCAN_PRIMARY_BASE 0x08006000U
#define XCAN_PRIMARY_SIZE 0x0000C800U
#define XCAN_SECONDARY_BASE 0x08012800U
#define XCAN_SECONDARY_SIZE 0x0000D000U
#define XCAN_PRODUCT_DATA_BASE 0x0801F800U
#define XCAN_PRODUCT_DATA_SIZE 0x00000800U

#define XCAN_IMAGE_HEADER_SIZE 0x00000200U
#define XCAN_APP_VECTOR_BASE (XCAN_PRIMARY_BASE + XCAN_IMAGE_HEADER_SIZE)
#define XCAN_SECONDARY_IMAGE_BASE (XCAN_SECONDARY_BASE + XCAN_FLASH_PAGE_SIZE)
#define XCAN_PRIMARY_TRAILER_BASE 0x08012000U
#define XCAN_SIGNED_IMAGE_MAX 0x0000C000U

#endif
